import {groq} from 'next-sanity'

export const blogPostQuery = groq`*[_type == "blogPost" && slug.current == $slug][0]{
  _id,
  title,
  slug,
  author,
  excerpt,
  mainImage{
    asset->{
      _id,
      url
    },
    alt
  },
  categories,
  tags,
  publishedAt,
  body,
  featured,
  seo{
    metaTitle,
    metaDescription
  }
}`

export const blogPostsQuery = groq`*[_type == "blogPost"] | order(publishedAt desc) {
  _id,
  title,
  slug,
  author,
  excerpt,
  mainImage{
    asset->{
      _id,
      url
    },
    alt
  },
  categories,
  tags,
  publishedAt,
  featured
}`

